
// Вычисляет площадь квадрата
double SquareArea(double side) {
    // Пример вызова: SquareArea(4.0) возвращает 16.0
    return side * side;
}

// Вычисляет периметр квадрата.
double SquarePerimeter(double side) {
    // Пример вызова: SquarePerimeter(4.0) возвращает 16.0
    return 4 * side;
}

// Вычисляет площадь прямоугольника.
double RectangleArea(double length, double width) {
    // Пример вызова: RectangleArea(3.0, 5.0) возвращает 15.0
    return length * width;
}

// Вычисляет периметр прямоугольника.
double RectanglePerimeter(double length, double width) {
    // Пример вызова: RectanglePerimeter(3.0, 5.0) возвращает 16.0
    return 2 * (length + width);
}